use std::fs;
use std::io;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

use crate::config::{Config, quality_for};
use crate::formats::{Format, action_name_de, action_name_en, quality_label};

const BINARY: &str = "istar-audio-converter";

/// Where a user's own menu lives, and where `--install-menu` writes unless `--menu-file` says otherwise.
pub fn user_menu_path() -> PathBuf {
    dirs::home_dir()
        .unwrap_or_else(|| PathBuf::from("."))
        .join(".local/share/kio/servicemenus/istar-audio-converter.desktop")
}

enum Entry {
    Separator,
    Action {
        id: &'static str,
        english: String,
        german: String,
        icon: &'static str,
        arguments: String,
    },
}

fn entries(config: &Config) -> Vec<Entry> {
    let fixed = |id, english: &str, german: &str, icon, arguments: &str| Entry::Action {
        id,
        english: english.to_string(),
        german: german.to_string(),
        icon,
        arguments: arguments.to_string(),
    };

    let mut entries: Vec<Entry> = Format::ALL
        .into_iter()
        .map(|format| {
            let label = quality_label(&quality_for(config, format));

            Entry::Action {
                id: format.action_id(),
                english: action_name_en(format, &label),
                german: action_name_de(format, &label),
                icon: format.icon(),
                arguments: format!("--format {} %F", format.key()),
            }
        })
        .collect();

    entries.extend([
        Entry::Separator,
        fixed(
            "extractAudio",
            "Extract Audio (no re-encoding)",
            "Audio extrahieren (ohne Neucodierung)",
            "audio-x-generic",
            "--extract %F",
        ),
        fixed(
            "extractConvert",
            "Extract && Convert Audio…",
            "Audio extrahieren && konvertieren…",
            "audio-x-generic",
            "--extract-convert %F",
        ),
        Entry::Separator,
        fixed(
            "configure",
            "Configure…",
            "Einstellungen…",
            "configure",
            "--configure",
        ),
    ]);

    entries
}

/// The whole service menu, with the configured quality in the names of the conversions. `directory`
/// is where the binary is installed: the service menu calls it by absolute path, because a Dolphin
/// session does not carry `~/.local/bin` in its PATH.
pub fn render(config: &Config, directory: &Path) -> String {
    let entries = entries(config);
    let mut separators = 0;
    let mut ids = Vec::new();
    let mut sections = String::new();

    for entry in &entries {
        match entry {
            Entry::Separator => {
                separators += 1;
                ids.push(format!("separator{separators}"));
                sections.push_str(&format!(
                    "\n[Desktop Action separator{separators}]\nName=\n"
                ));
            }
            Entry::Action {
                id,
                english,
                german,
                icon,
                arguments,
            } => {
                ids.push((*id).to_string());
                sections.push_str(&format!(
                    "\n[Desktop Action {id}]\nName={english}\nName[de]={german}\nIcon={icon}\nExec={}/{BINARY} {arguments}\n",
                    directory.display()
                ));
            }
        }
    }

    format!(
        "# Generated by {BINARY} --install-menu - the quality in the names is --configure's, not an edit.\n\
         [Desktop Entry]\n\
         Type=Service\n\
         X-KDE-ServiceTypes=KonqPopupMenu/Plugin\n\
         MimeType=audio/*;video/*;\n\
         Actions={};\n\
         X-KDE-Priority=TopLevel\n\
         X-KDE-Submenu=Audio Converter\n\
         X-KDE-Submenu[de]=Audio-Konverter\n\
         {sections}",
        ids.join(";")
    )
}

/// Write the menu where KDE reads it. A temp file and a rename in the same directory, so a crash
/// mid-write never leaves a truncated `.desktop` behind; KonqPopupMenu ignores one that is not
/// executable.
pub fn write(config: &Config, directory: &Path, path: &Path) -> io::Result<PathBuf> {
    let path = path.to_path_buf();
    let temporary = path.with_extension("tmp");

    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }

    fs::write(&temporary, render(config, directory))?;
    fs::set_permissions(&temporary, fs::Permissions::from_mode(0o755))?;
    fs::rename(&temporary, &path)?;

    Ok(path)
}

/// After `--configure`: bring the names up to date, but only where there is a menu already - a run
/// from a terminal on a machine that never installed one should not create it. A package's menu
/// under a system data directory cannot be rewritten, so the user gets a copy of their own in its
/// place: KDE takes a user's menu over a system one of the same name.
pub fn refresh(config: &Config, directory: &Path) {
    let path = user_menu_path();

    if path.exists() || system_menu_exists() {
        let _ = write(config, directory, &path);
    }
}

/// Whether a package installed the menu, in any of the data directories KDE reads service menus from.
fn system_menu_exists() -> bool {
    let directories = std::env::var("XDG_DATA_DIRS")
        .ok()
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| "/usr/local/share:/usr/share".to_string());

    directories.split(':').any(|directory| {
        Path::new(directory)
            .join("kio/servicemenus")
            .join(format!("{BINARY}.desktop"))
            .exists()
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn defaults() -> Config {
        Format::ALL
            .into_iter()
            .map(|format| (format, format.default_quality().to_string()))
            .collect()
    }

    fn menu(config: &Config) -> String {
        render(config, Path::new("/opt/bin"))
    }

    #[test]
    fn the_actions_come_in_the_order_the_menu_shows_them() {
        assert!(menu(&defaults()).contains(
            "Actions=convertToMp3;convertToOgg;convertToFlac;convertToWav;convertToM4a;\
             convertToOpus;convertToAlac;separator1;extractAudio;extractConvert;separator2;configure;\n"
        ));
    }

    #[test]
    fn every_listed_action_has_its_section() {
        let text = menu(&defaults());
        let listed = text
            .lines()
            .find_map(|line| line.strip_prefix("Actions="))
            .unwrap();

        for id in listed.split(';').filter(|id| !id.is_empty()) {
            assert!(
                text.contains(&format!("\n[Desktop Action {id}]\n")),
                "{id} has no section"
            );
        }
    }

    #[test]
    fn the_configured_quality_is_in_the_name() {
        let mut config = defaults();
        config.insert(Format::Mp3, "V2".to_string());

        let text = menu(&config);

        assert!(text.contains("Name=Convert to MP3 (V2)\n"));
        assert!(text.contains("Name[de]=In MP3 konvertieren (V2)\n"));
        assert!(
            text.contains("Name=Convert to FLAC\n"),
            "lossless has no label"
        );
    }

    #[test]
    fn the_binary_is_called_by_its_absolute_path() {
        let text = menu(&defaults());

        assert!(text.contains("Exec=/opt/bin/istar-audio-converter --format opus %F\n"));
        assert!(text.contains("Exec=/opt/bin/istar-audio-converter --configure\n"));
    }

    #[test]
    fn a_package_menu_goes_where_it_is_told_with_the_default_qualities() {
        let directory = std::env::temp_dir().join(format!("audio-menu-{}", std::process::id()));
        let path = directory.join("share/kio/servicemenus/istar-audio-converter.desktop");

        let written = write(&Config::new(), Path::new("/usr/bin"), &path).unwrap();
        let text = fs::read_to_string(&written).unwrap();
        let mode = fs::metadata(&written).unwrap().permissions().mode();
        fs::remove_dir_all(&directory).unwrap();

        assert_eq!(written, path);
        assert_eq!(text, render(&defaults(), Path::new("/usr/bin")));
        assert!(text.contains("Exec=/usr/bin/istar-audio-converter --format opus %F\n"));
        assert_eq!(
            mode & 0o111,
            0o111,
            "KonqPopupMenu ignores a menu that is not executable"
        );
    }
}
